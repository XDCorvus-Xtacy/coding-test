'''
오래전 유행했던 콜라 문제가 있습니다. 콜라 문제의 지문은 다음과 같습니다.

정답은 아무에게도 말하지 마세요.
콜라 빈 병 2개를 가져다주면 콜라 1병을 주는 마트가 있다. 빈 병 20개를 
가져다주면 몇 병을 받을 수 있는가?
단, 보유 중인 빈 병이 2개 미만이면, 콜라를 받을 수 없다.

문제를 풀던 상빈이는 콜라 문제의 완벽한 해답을 찾았습니다. 상빈이가 푼 방법은 
아래 그림과 같습니다. 우선 콜라 빈 병 20병을 가져가서 10병을 받습니다. 
받은 10병을 모두 마신 뒤, 가져가서 5병을 받습니다. 5병 중 4병을 모두 마신 뒤 
가져가서 2병을 받고, 또 2병을 모두 마신 뒤 가져가서 1병을 받습니다. 받은 1병과 
5병을 받았을 때 남은 1병을 모두 마신 뒤 가져가면 1병을 또 받을 수 있습니다. 
이 경우 상빈이는 총 10 + 5 + 2 + 1 + 1 = 19병의 콜라를 받을 수 있습니다.

문제를 열심히 풀던 상빈이는 일반화된 콜라 문제를 생각했습니다. 이 문제는 빈 병 
a개를 가져다주면 콜라 b병을 주는 마트가 있을 때, 빈 병 n개를 가져다주면 몇 병을 
받을 수 있는지 계산하는 문제입니다. 기존 콜라 문제와 마찬가지로, 보유 중인 빈 병이 
a개 미만이면, 추가적으로 빈 병을 받을 순 없습니다. 상빈이는 열심히 고심했지만, 
일반화된 콜라 문제의 답을 찾을 수 없었습니다. 상빈이를 도와, 일반화된 콜라 문제를 
해결하는 프로그램을 만들어 주세요.
콜라를 받기 위해 마트에 주어야 하는 병 수 a, 빈 병 a개를 가져다 주면 마트가 주는 
콜라 병 수 b, 상빈이가 가지고 있는 빈 병의 개수 n이 매개변수로 주어집니다. 상빈이가 
받을 수 있는 콜라의 병 수를 return 하도록 solution 함수를 작성해주세요.

제한사항
1 ≤ b < a ≤ n ≤ 1,000,000
정답은 항상 int 범위를 넘지 않게 주어집니다.
'''
def solution(a, b, n):
    cola = 0
    while n >= a:
        received = b*(n//a)
        cola += received
        n = received + n%a
    return cola

def solution(a, b, n):
    return (n-b)//(a-b)*b

'''
n-b가 통하는 이유

-b의 실제 효력은 나눗셈 마지막 부분에서 발휘된다.
나눗셈은 뺄셈의 누적이다. 위 문제는 n-a+b가 반복된다.
n이 충분히 클 때는 n - (a-b)로 계산해도 문제 없다.
하지만 누적 결과 n이 a보다 작아진 경우는
n-a+b와 n-(a-b)는 다르다.
n이 a보다 작은 경우는 교환이 불가능하기에 집계되어선 안 된다.
하지만 후자의 경우(예: n=3, a=4, b=2)에는 n < a여도 집계가 된다.
이를 방지하기 위해서 양 변에 같은 식을 취하는 것이다.
우리가 확인할 것은 원래 a, b이다.
n >= a
여기에서
n - b >= a -b
이 두 논리는 같은 논리이다.
결국 n이 a보다 큰지 아닌지를 확인하기 위함이고 크다면 한번 더 집계할 수 있다는 뜻이므로
(n - b) // (a - b)로도 교환횟수가 정확히 누적되는 것이다.


결론
n-b가 통하는 이유

1. 나눗셈은 뺄셈의 누적이다.
   n // (a-b) 는 "n에서 (a-b)를 몇 번 뺄 수 있나"를 센다.
   즉 // 가 판단하는 문턱은 (a-b)이다.

2. 그런데 이 문제의 실제 교환 조건은 "병 >= a" 이다.
   n이 충분히 클 때는 n-a+b와 n-(a-b)가 같아 문제없지만,
   경계(n < a)에서 갈린다.
   예: n=3, a=4, b=2 → 실제로는 교환 불가이나
       n-(a-b) = 3-2 = 1 이라 // 는 1회로 집계한다.

3. 두 문턱의 차이가 정확히 b이므로, 양변에서 b를 빼 정렬한다.
   n >= a  ⟺  n-b >= a-b   (같은 조건)
   따라서 (n-b) // (a-b) 가 정확한 교환 횟수가 된다.

4. -b는 중간 과정에는 영향을 주지 않고 경계에서만 효력을 발휘하므로
   전체 계산이 어긋나지 않는다.
'''