# practice DP - 계단 1: 1차원 max DP
'''
[문제]
숫자가 적힌 칸이 일렬로 있습니다. (예: [10, 20, 15, 30])
원하는 칸을 골라 그 점수를 얻는데, 인접한 두 칸은 동시에 고를 수 없습니다.
얻을 수 있는 최대 점수를 구하세요.

  예) [10, 20, 15, 30] → 50   (20 + 30)
      [4, 5, 4]        → 8    (4 + 4)
      [10, 5]          → 10   (10 하나만)

[그리디로 안 되는 이유]
큰 것부터 고르면 [4, 5, 4] 에서 5를 먹는 순간 양옆이 막혀 5로 끝남.
"지금 최선"이 나중에 후회를 남기므로 그리디가 성립하지 않음.

[DP 3질문]
Q1 상태 : dp[i] = "i번 칸까지만 있을 때의 최대 점수"
Q2 점화식: dp[i] = max(dp[i-1], dp[i-2] + arr[i])
           · 안 고른다 → i-1번까지의 답 그대로
           · 고른다   → i-1번은 인접이라 못 쓰므로 dp[i-2] + 현재 점수
Q3 초기값: dp[0] = arr[0]
           dp[1] = max(arr[0], arr[1])   ← 둘은 인접이라 하나만 고름

[핵심]
dp의 인덱스는 "몇 번째 경우"가 아니라 "문제의 크기"
각 칸에는 그 크기의 문제를 풀었을 때의 답 하나가 들어감
'''
def max_score(arr):
    n = len(arr)
    if n == 1:
        return arr[0]
    dp = [0] * n
    dp[0] = arr[0]
    dp[1] = max(arr[0], arr[1])
    for i in range(2, n):
        dp[i] = max(dp[i-1], dp[i-2] + arr[i])
    return dp[-1]






'''
N행 2열짜리 땅이 있습니다.  예: [[1, 2], [3, 4], [5, 6]]
1행부터 한 행씩 내려오며, 각 행의 2칸 중 한 칸만 밟습니다.
같은 열을 연속해서 밟을 수 없습니다.
마지막 행까지 내려왔을 때 최대 점수는?
'''
def max_score2(arr):
    n = len(arr)
    dp = [[0, 0] for _ in range(n)]
    dp[0][0] = arr[0][0]
    dp[0][1] = arr[0][1]
    for i in range(1, n):
        dp[i][0] = dp[i-1][1] + arr[i][0]
        dp[i][1] = dp[i-1][0] + arr[i][1]
    return max(dp[-1])