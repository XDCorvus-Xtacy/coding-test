'''
계단 1과 완전히 같은 문제. 방식만 뒤집습니다.

count_divisors_fast(n)

정수 n이 주어질 때, 1부터 n까지 각 수의 약수 개수를 리스트로 반환

조건: 나눗셈·나머지 연산(%, //)을 한 번도 쓰지 않을 것

예) n = 10
→ [0, 1, 2, 2, 3, 2, 4, 2, 4, 3, 4]   (계단 1과 동일해야 함)
'''
def count_divisors_fast(n):
     cnt = [0]*(n+1)
     for i in range(1, n+1):
          for j in range(i, n+1, i):
               cnt[j] += 1

     return cnt


##################################################
# ── 계단 3: 안쪽 루프 총 횟수 ────────────────
# i가 주어지면 안쪽 루프는 n//i 번 돈다
# 전부 더하면 n//1 + n//2 + ... + n//n
# n으로 묶으면 n × (1 + 1/2 + ... + 1/n)
# 조화수가 log n인 이유:
#   항을 1, 2, 4, 8...개씩(2의 거듭제곱) 묶으면 묶음마다 합이 약 1/2.
#   묶음 개수는 2를 몇 번 제곱해야 n이 되는가 = log2(n).
#   따라서 총합 ≈ (1/2) × log2(n) → 상수 무시 → O(log n)
#
# 최종: n × O(log n) = O(n log n)
#   n=10^6 → 약 1,400만  (수 중심 n√n은 약 6~7억)
##################################################
def count_inner_loops(n):
     cnt = 0
     for i in range(1, n+1):
          for j in range(i, n+1, i):
               cnt += 1
     return cnt

print(count_inner_loops(12))  # 35